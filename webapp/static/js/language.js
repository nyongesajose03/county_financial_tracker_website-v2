    function normalize(value) {
        return value.replace(/\s+/g, ' ').trim();
    }

    function translateTextNode(node) {
        const original = node.nodeValue;
        const key = normalize(original);
        let translated = translations[key];
        if (!translated) {
            const chartPoint = key.match(/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec): KES ([\d,]+)$/);
            if (chartPoint) {
                translated = `${translations[chartPoint[1]]}: KES ${chartPoint[2]}`;
            }
        }
        if (translated) {
            const leading = original.match(/^\s*/)[0];
            const trailing = original.match(/\s*$/)[0];
            node.nodeValue = `${leading}${translated}${trailing}`;
        }
    }

    function translateElement(element) {
        const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
        while (walker.nextNode()) {
            const node = walker.currentNode;
            if (!node.parentElement.closest('script, style, noscript')) {
                translateTextNode(node);
            }
        }

        element.querySelectorAll('input[placeholder], textarea[placeholder], [title], [aria-label], [alt]').forEach((item) => {
            ['placeholder', 'title', 'aria-label', 'alt'].forEach((attribute) => {
                const value = item.getAttribute(attribute);
                const translated = value && translations[normalize(value)];
                if (translated) {
                    item.setAttribute(attribute, translated);
                }
            });
        });
    }

    function applyLanguage(language) {
        const isSwahili = language === 'sw';
        document.documentElement.lang = isSwahili ? 'sw' : 'en';
        if (isSwahili) {
            document.title = translations[normalize(document.title)] || document.title;
            translateElement(document.body);
        } else {
            window.location.reload();
        }
    }

    document.addEventListener('DOMContentLoaded', () => {
        const language = localStorage.getItem(languageKey) || 'en';
        const languageSetting = document.getElementById('language-setting');
        if (languageSetting) {
            languageSetting.value = language;
            languageSetting.addEventListener('change', () => {
                localStorage.setItem(languageKey, languageSetting.value);
                window.location.reload();
            });
        }

        if (language === 'sw') {
            applyLanguage(language);
            const observer = new MutationObserver((mutations) => {
                mutations.forEach((mutation) => {
                    mutation.addedNodes.forEach((node) => {
                        if (node.nodeType === Node.TEXT_NODE) {
                            translateTextNode(node);
                        } else if (node.nodeType === Node.ELEMENT_NODE) {
                            translateElement(node);
                        }
                    });
                    if (mutation.type === 'characterData') {
                        translateTextNode(mutation.target);
                    }
                });
            });
            observer.observe(document.body, { childList: true, subtree: true, characterData: true });
        }
    });
